#!/usr/bin/env python3
"""Generate the TikZ curves and pooled table rows for the U-limit section."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
CHART = HERE / "06_chaining_u_batch_chart.tex"
TABLE = HERE / "06_chaining_u_batch_table.tex"
WIDTHS = (2, 4, 8, 16, 32, 64)
STYLES = {
    2: "draw=chainBlue!95!black,line width=.85pt",
    4: "draw=chainBlue!95!black,line width=.85pt,densely dashed",
    8: "draw=chainOrange!95!black,line width=.85pt",
    16: "draw=chainOrange!95!black,line width=.85pt,densely dashed",
    32: "draw=chainGreen!80!black,line width=.85pt",
    64: "draw=chainGreen!80!black,line width=.85pt,densely dashed",
}


def find_results() -> Path:
    for parent in HERE.parents:
        candidate = parent / "CHAINING_BRANCHING_U_BATCH_EXPERIMENT_RESULTS.yaml"
        if candidate.exists():
            return candidate
    raise FileNotFoundError("cannot locate U-counter result YAML above the chapter")


def coordinates(curve: list[dict[str, object]], width: int) -> str:
    points = []
    for point in curve:
        x = float(point["declared_divergence_percent"])
        widths = point["widths"]
        assert isinstance(widths, dict)
        entry = widths[str(width)]
        assert isinstance(entry, dict)
        derived = entry["derived"]
        assert isinstance(derived, dict)
        y = float(derived["u_batch_reduction_pct"])
        points.append(f"({x:.2f},{y:.4f})")
    return " ".join(points)


def make_chart(document: dict[str, object]) -> str:
    aggregates = document["aggregates"]
    assert isinstance(aggregates, dict)
    curves = aggregates["divergence_curves"]
    assert isinstance(curves, dict)
    lines = [
        "% Generated by 06_chaining_u_batch_plot.py; do not hand-edit.",
        "\\begin{tikzpicture}[font=\\scriptsize]",
    ]
    legend_x = (2.10, 3.95, 5.80, 7.65, 9.50, 11.35)
    for x, width in zip(legend_x, WIDTHS):
        lines.append(
            f"  \\draw[{STYLES[width]}] ({x:.2f},3.75)--({x + .42:.2f},3.75) "
            f"node[anchor=west,text=black] {{$L={width}$}};"
        )
    panels = (
        ("random_occurrences", "(a)", 1.15),
        ("mosaic", "(b)", 7.85),
    )
    for construction, title, x_shift in panels:
        lines.extend(
            [
                f"  \\begin{{scope}}[shift={{({x_shift:.2f},.55)}},x=.25cm,y=.027cm]",
                "    \\foreach \\y in {0,25,50,75,100} {",
                "      \\draw[black!14] (0,\\y)--(20,\\y);",
                "      \\draw (-.18,\\y)--(0,\\y);",
                "      \\node[anchor=east,xshift=-1pt] at (0,\\y) {\\y};",
                "    }",
                "    \\foreach \\x in {0,5,10,15,20} {",
                "      \\draw (\\x,0)--(\\x,-3.3);",
                "      \\node[anchor=north,yshift=-1pt] at (\\x,0) {\\x};",
                "    }",
                "    \\draw[->] (0,0)--(20.6,0);",
                "    \\draw[->] (0,0)--(0,105);",
            ]
        )
        curve = curves[construction]
        assert isinstance(curve, list)
        for width in WIDTHS:
            lines.append(
                f"    \\draw[{STYLES[width]}] plot coordinates "
                f"{{{coordinates(curve, width)}}};"
            )
        lines.extend(
            [
                "  \\end{scope}",
                f"  \\node[anchor=north west,font=\\bfseries,fill=white,inner sep=1pt] "
                f"at ({x_shift + .08:.2f},3.20) {{{title}}};",
                f"  \\node[anchor=north] at ({x_shift + 2.50:.2f},.14) {{divergence (\\%)}};",
            ]
        )
    lines.append(
        "  \\node[rotate=90,anchor=south] at (.10,1.90) "
        "{$\\operatorname{Reduction}^{U}_{L}$ (\\%)};"
    )
    lines.append("\\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def make_table(document: dict[str, object]) -> str:
    aggregates = document["aggregates"]
    assert isinstance(aggregates, dict)
    by_construction = aggregates["by_construction"]
    assert isinstance(by_construction, dict)
    curves = aggregates["divergence_curves"]
    assert isinstance(curves, dict)

    def cells(derived_by_width: dict[str, object]) -> list[str]:
        result = []
        for width in WIDTHS:
            entry = derived_by_width[str(width)]
            assert isinstance(entry, dict)
            derived = entry["derived"]
            assert isinstance(derived, dict)
            no_update = float(derived["no_update_batch_rate_pct"])
            reduction = float(derived["u_batch_reduction_pct"])
            result.append(f"{no_update:.1f}/{reduction:.1f}")
        return result

    def curve_widths(construction: str, divergence: float) -> dict[str, object]:
        curve = curves[construction]
        assert isinstance(curve, list)
        for point in curve:
            assert isinstance(point, dict)
            if float(point["declared_divergence_percent"]) == divergence:
                widths = point["widths"]
                assert isinstance(widths, dict)
                return widths
        raise ValueError(f"missing divergence {divergence} for {construction}")

    blocks = (
        (
            r"0\% divergence",
            (
                ("Random occurrences", curve_widths("random_occurrences", 0.0)),
                ("Mosaic", curve_widths("mosaic", 0.0)),
            ),
        ),
        (
            r"10\% divergence",
            (
                ("Random occurrences", curve_widths("random_occurrences", 10.0)),
                ("Degraded mosaic", curve_widths("mosaic", 10.0)),
            ),
        ),
        (
            "Pooled",
            (
                ("Random occurrences", by_construction["random_occurrences"]),
                ("Mosaic and Degraded mosaic", by_construction["mosaic"]),
                ("Spaced copy", by_construction["spaced_copies"]),
                ("Narrow-gap spaced-copy", by_construction["constructed_coordinate_control"]),
            ),
        ),
    )
    lines = ["% Generated by 06_chaining_u_batch_plot.py; do not hand-edit."]
    for block_index, (subset, rows) in enumerate(blocks):
        for row_index, (label, widths) in enumerate(rows):
            assert isinstance(widths, dict)
            subset_cell = subset if row_index == 0 else ""
            lines.append(subset_cell + " & " + label + " & " + " & ".join(cells(widths)) + r"\\")
        if block_index + 1 < len(blocks):
            lines.append(r"\cmidrule(lr){1-8}")
    lines[-1] = lines[-1][:-2]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=find_results())
    arguments = parser.parse_args()
    document = json.loads(arguments.results.read_text(encoding="utf-8"))
    if document.get("experiment_status") != "complete_pass":
        raise ValueError("refusing to plot an incomplete experiment")
    CHART.write_text(make_chart(document), encoding="utf-8")
    TABLE.write_text(make_table(document), encoding="utf-8")
    print(CHART)
    print(TABLE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
