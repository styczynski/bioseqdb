#!/usr/bin/env python3
"""Generate `dynamic_huffman_skip_lut.cppm` from upstream's CSV.

The upstream LUT (`librapidarchive-master/src/rapidgzip/blockfinder/
NEXT_DYNAMIC_DEFLATE_CANDIDATE_LUT_15.csv`) contains 32768 signed
integers in [-13, 15]:

  * Positive values  → "skip N bits — no candidate possible".
  * Negative values  → "candidate at offset abs(N); validate further".

We pack as `int8_t` (32 KiB on disk + in the binary), preserving the
sign convention.

Usage:

  python3 build_dynamic_lut.py \
      --csv librapidarchive-master/src/rapidgzip/blockfinder/NEXT_DYNAMIC_DEFLATE_CANDIDATE_LUT_15.csv \
      --out main/bioseq/io/compression/dynamic_huffman_skip_lut.cppm
"""
from __future__ import annotations

import argparse
import pathlib

PROLOGUE = """\
/**
 * @file dynamic_huffman_skip_lut.cppm
 * @brief 32 KiB constexpr skip-LUT for the dynamic-Huffman blockfinder.
 *
 * Generated by `compression/tools/build_dynamic_lut.py` from upstream
 * librapidarchive's `NEXT_DYNAMIC_DEFLATE_CANDIDATE_LUT_15.csv`. Each
 * entry is `int8_t`; positive = "skip N bits before next candidate",
 * negative = "candidate at offset abs(N); pass to precode validator".
 *
 * Imported by `compression/blockfinder.cppm` only.
 */
module;

#include "common.h"

#include <array>
#include <cstdint>

export module bioseq_io.compression.dynamic_huffman_skip_lut;

export namespace bioseq::io::compression {

inline constexpr std::array<std::int8_t, 32768> kDynamicHuffmanSkipLut = {{
"""

EPILOGUE = """\
}};

}  // namespace bioseq::io::compression
"""


def parse_csv(path: pathlib.Path) -> list[int]:
    values: list[int] = []
    for line in path.read_text().splitlines():
        for fragment in line.split(","):
            fragment = fragment.strip()
            if not fragment:
                continue
            values.append(int(fragment))
    return values


def emit(out: pathlib.Path, values: list[int]) -> None:
    if len(values) != 32768:
        raise ValueError(
            f"expected 32768 entries; got {len(values)}"
        )
    lines: list[str] = []
    for row_start in range(0, len(values), 16):
        row = values[row_start:row_start + 16]
        lines.append(
            "    " + ", ".join(f"{v:>4}" for v in row) + ","
        )
    out.write_text(PROLOGUE + "\n".join(lines) + "\n" + EPILOGUE)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=pathlib.Path)
    parser.add_argument("--out", required=True, type=pathlib.Path)
    args = parser.parse_args()
    values = parse_csv(args.csv)
    emit(args.out, values)


if __name__ == "__main__":
    main()
