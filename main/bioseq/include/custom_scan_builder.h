#include "pg_version_compat.h"

class CustomPathNodeData {
private:
    PList<void> data;
public:
    CustomPathNodeData(const List* arg_list) : data(arg_list) {}
    CustomPathNodeData() : data(PList<void>::nulls<3>()) {}

    PList<Node> plainClauses() const {
        return PList<Node>(static_cast<const List*>(data[0]));
    }
    
    PList<Node> allClauses() const {
        return PList<Node>(static_cast<const List*>(data[1]));
    }

    PList<Node> vectorizedNodes() const {
        return PList<Node>(static_cast<const List*>(data[2]));
    }

    const List* ptr() const {
        return data.ptr();
    }
};


